"""Maintain the generated executable handoff block from one reviewed source.

This is a stdlib-only development/build tool, never a Core runtime dependency.
It parses but never executes the bootstrap source. Builds call check(), while
maintainers explicitly use --write after editing tools/pyz_bootstrap.py.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys

BEGIN = b"<!-- BEGIN GENERATED PYZ BOOTSTRAP: tools/pyz_bootstrap.py -->\n"
END = b"<!-- END GENERATED PYZ BOOTSTRAP -->"
CODE_PREFIX = b"```python\n# PATCHHARBOR-PYZ-BOOTSTRAP\n"
CAP_BEGIN = b"# BEGIN GENERATED RUNTIME CAPABILITIES\n"
CAP_END = b"# END GENERATED RUNTIME CAPABILITIES"


def render_capabilities(source: bytes, contract: bytes) -> bytes:
    """Copy reviewed literals without executing a bootstrap or product import."""
    tree = ast.parse(contract, feature_version=(3, 10))
    names = ('OPERATIONS', 'TASK_FORMATS', 'RESULT_FORMATS')
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in names:
                    if target.id in values:
                        raise ValueError('ambiguous capability literal')
                    values[target.id] = ast.literal_eval(node.value)
    if set(values) != set(names):
        raise ValueError('missing capability literal')
    for name, value in values.items():
        expected_type = str if name == 'OPERATIONS' else int
        if (type(value) is not tuple or not value
                or any(type(v) is not expected_type for v in value)
                or len(set(value)) != len(value)
                or any(not v if expected_type is str else v < 1 for v in value)):
            raise ValueError('invalid capability literal')
    source = source.replace(b'\r\n', b'\n').replace(b'\r', b'\n')
    if source.count(CAP_BEGIN) != 1 or source.count(CAP_END) != 1:
        raise ValueError('expected exactly one capability region')
    before, _, rest = source.partition(CAP_BEGIN)
    _, separator, after = rest.partition(CAP_END)
    if not separator:
        raise ValueError('capability markers out of order')
    literals = ''.join(f'{name} = {values[name]!r}\n' for name in names).encode()
    generated = before + CAP_BEGIN + literals + CAP_END + after
    ast.parse(generated, feature_version=(3, 10))
    return generated


def render(template: bytes, source: bytes) -> bytes:
    """Replace exactly one executable region; retain all surrounding bytes."""
    if template.count(BEGIN) != 1 or template.count(END) != 1:
        raise ValueError("expected exactly one generated bootstrap region")
    before, _, remainder = template.partition(BEGIN)
    _, separator, after = remainder.partition(END)
    if not separator:
        raise ValueError("generated bootstrap markers are out of order")
    # Git checkouts may use CRLF for Python sources. The generated program has
    # canonical LF bytes; the independently maintained document is untouched.
    program = source.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
    ast.parse(program, filename="tools/pyz_bootstrap.py", feature_version=(3, 10))
    if not program.strip() or any(line.startswith("```") for line in program.splitlines()):
        raise ValueError("bootstrap source is empty or would terminate its code block")
    if BEGIN.decode().strip() in program or END.decode() in program:
        raise ValueError("bootstrap source contains generated-region markers")
    if not program.endswith("\n"):
        program += "\n"
    generated = before + BEGIN + CODE_PREFIX + program.encode("utf-8") + b"```\n" + END + after
    if generated.count(CODE_PREFIX) != 1:
        raise ValueError("another executable bootstrap exists outside the generated region")
    return generated


def _contents(root: Path) -> tuple[tuple[Path, bytes, bytes], ...]:
    script = root / 'tools/pyz_bootstrap.py'
    source = script.read_bytes()
    program = render_capabilities(source, (root / 'src/patchharbor/runtime_contract.py').read_bytes())
    target = root / "CHAT_INSTRUCTIONS.md"
    original = target.read_bytes()
    generated = render(original, program)
    return ((script, source, program), (target, original, generated))


def check(root: Path) -> None:
    """Reject stale generated bytes without modifying the source checkout."""
    if any(generated != (original.replace(b'\r\n', b'\n').replace(b'\r', b'\n')
                             if path.suffix == '.py' else original)
           for path, original, generated in _contents(root)):
        raise ValueError("stale bootstrap: run python scripts/render_chat_bootstrap.py --write")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--write", action="store_true")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    if args.check:
        check(args.root)
    else:
        # Validate both outputs completely before writing either file.
        for target, original, generated in _contents(args.root):
            if generated != original:
                target.write_bytes(generated)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, SyntaxError) as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1)
